/**
 * Generates supabase/seed/0001_catalog.sql from the JSON catalog + image manifest.
 * This is the single source of truth: no hand-copied prices, coordinates or records.
 * Run: node scripts/generate-supabase-seed.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'packages', 'catalog', 'src', 'data');
const read = (name) => JSON.parse(readFileSync(join(dataDir, name), 'utf8'));
const manifest = JSON.parse(readFileSync(join(root, 'assets', 'images', 'IMAGE_SOURCES.json'), 'utf8'));

const out = [];
const emit = (s) => out.push(s);
const q = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${String(v).replace(/'/g, "''")}'`;
};
const jq = (v) => `${q(JSON.stringify(v ?? null))}::jsonb`;
const arr = (v) => v && v.length ? `ARRAY[${v.map(q).join(',')}]::text[]` : `'{}'::text[]`;
const num = (v) => v === null || v === undefined ? 'NULL' : String(Number(v));
const slug = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');

const destinations = read('destinations.json');
const hiddenGems = read('hidden-gems.json');
const attractions = read('attractions.json');
const places = read('places.json');
const vehicles = read('vehicles.json');
const sharedRoutes = read('shared-taxi-routes.json');
const properties = read('properties.json');
const restaurants = read('restaurants.json');
const groceryStores = read('grocery-stores.json');
const packages = read('tour-packages.json');
const experiences = read('experiences.json');

emit(`-- Generated by scripts/generate-supabase-seed.mjs on ${new Date().toISOString().slice(0, 10)}.`);
emit('-- Source: packages/catalog/src/data/*.json and assets/images/IMAGE_SOURCES.json. DO NOT EDIT BY HAND.');
emit('BEGIN;');
emit('');

// ---- image provenance -----------------------------------------------------
for (const a of manifest.assets) {
  const displayable = a.displayed !== false && a.license !== 'UNVERIFIED';
  emit(`INSERT INTO public.image_sources (id, place, depicts, source_url, original_file_url, author, license, license_url, displayable, verification, download_date, local_path, alt) VALUES
(${q(a.id)}, ${q(a.place)}, ${q(a.depicts)}, ${q(a.sourceUrl)}, ${q(a.originalFileUrl)}, ${q(a.author)}, ${q(a.license)}, ${q(a.licenseUrl || '')}, ${q(displayable)}, ${q(a.verification)}, ${q(a.downloadDate)}::date, ${q(a.localOriginal)}, ${q(a.alt)})
ON CONFLICT (id) DO NOTHING;`);
}
emit('');

// ---- destinations + images ------------------------------------------------
for (const d of destinations) {
  emit(`INSERT INTO public.destinations (id, slug, name, region, state, country, lat, lng, coordinate_accuracy, elevation_m, elevation_verified, description, best_season, estimated_visit_hours, hidden_gem, activities, accessibility, safety, weather_note, sources, info_status)
VALUES (${q(d.id)}, ${q(d.slug)}, ${q(d.name)}, ${q(d.region)}, ${q(d.state)}, ${q(d.country)}, ${num(d.coords.lat)}, ${num(d.coords.lng)},
${q(d.coordinateAccuracy)}, ${num(d.elevationM)}, ${q(d.elevationVerified)}, ${q(d.description)}, ${q(d.bestSeason)}, ${num(d.estimatedVisitHours)},
${q(d.hiddenGem)}, ${arr(d.activities)}, ${q(d.accessibility)}, ${q(d.safety)}, ${q(d.weatherNote)}, ${jq(d.sources)}, ${q(d.infoStatus)})
ON CONFLICT (id) DO NOTHING;`);
  let order = 0;
  for (const im of d.images) {
    const src = manifest.assets.find((a) => a.sourceUrl === im.sourceUrl);
    const verified = im.status === 'verified' && im.assetPath && im.license;
    emit(`INSERT INTO public.destination_images (destination_id, image_source_id, status, asset_path, thumb_path, alt, credit, license, source_url, sort_order)
VALUES (${q(d.id)}, ${q(src ? src.id : null)}, ${q(verified ? 'verified' : 'unavailable')}, ${q(verified ? im.assetPath : null)},
${q(verified ? (im.thumbPath || im.assetPath) : null)}, ${q(im.alt)}, ${q(verified ? im.credit : null)}, ${q(verified ? im.license : null)},
${q(verified ? im.sourceUrl : null)}, ${order++})
ON CONFLICT (destination_id, asset_path) DO NOTHING;`);
  }
}
emit('');

// ---- places and vehicle rate card -----------------------------------------
for (const p of places) {
  emit(`INSERT INTO public.places (id, name, address, locality, kind, lat, lng) VALUES
(${q(p.id)}, ${q(p.name)}, ${q(p.address || null)}, ${q(p.locality || null)}, ${q(p.kind || 'address')}, ${num(p.lat)}, ${num(p.lng)})
ON CONFLICT (id) DO NOTHING;`);
}
for (const v of vehicles) {
  emit(`INSERT INTO public.vehicle_classes (id, name, seats, base_fare_paise, per_km_paise, per_min_paise, min_fare_paise, luggage, tags) VALUES
(${q(v.id)}, ${q(v.name)}, ${num(v.seats)}, ${num(v.baseFarePaise)}, ${num(v.perKmPaise)}, ${num(v.perMinutePaise)}, ${num(v.minimumFarePaise)}, ${q(v.category)}, ${arr([v.category, v.description])})
ON CONFLICT (id) DO NOTHING;`);
}
emit('');

// ---- attractions and routes ------------------------------------------------
for (const a of attractions) {
  const src = a.image?.status === 'verified' ? manifest.assets.find((x) => x.sourceUrl === a.image.sourceUrl) : null;
  emit(`INSERT INTO public.destination_attractions (id, destination_id, name, description, category, lat, lng, typical_visit_minutes, image_source_id, image_status, info_status)
VALUES (${q(a.id)}, ${q(a.destinationId)}, ${q(a.name)}, ${q(a.description)}, ${q(a.category)}, ${num(a.coords.lat)}, ${num(a.coords.lng)},
${num(a.typicalVisitMinutes)}, ${q(src ? src.id : null)}, ${q(a.image?.status === 'verified' ? 'verified' : 'unavailable')}, ${q(a.infoStatus)})
ON CONFLICT (id) DO NOTHING;`);
}
const bagdogra = places.find((p) => p.id === 'plc_bagdogra');
const haversine = (a, b) => {
  const R = 6371, rad = (x) => x * Math.PI / 180;
  const dLat = rad(b.lat - a.lat), dLng = rad(b.lng - a.lng);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(rad(a.lat)) * Math.cos(rad(b.lat)) * Math.sin(dLng / 2) ** 2;
  return Math.round(2 * R * Math.asin(Math.sqrt(h)) * 100) / 100;
};
for (const d of destinations) {
  emit(`INSERT INTO public.destination_routes (destination_id, from_place_id, to_place_id, mode, distance_km, duration_min, lat, lng, note, source)
VALUES (${q(d.id)}, ${q(bagdogra?.id || null)}, ${q(d.id)}, 'road', ${num(haversine(bagdogra, d.coords) * 1.35)},
${num(Math.round(haversine(bagdogra, d.coords) * 1.35 / 32 * 60 + 12))}, ${num(d.coords.lat)}, ${num(d.coords.lng)},
${q('Great-circle road-factor estimate from Bagdogra Airport (IXB). Configure a directions provider for road-accurate routing.')}, ${q('gowayy-location-engine')});`);
}
for (const g of hiddenGems) {
  emit(`INSERT INTO public.destination_routes (destination_id, from_place_id, mode, distance_km, lat, lng, note, source)
VALUES (${q(g.destinationId)}, ${q(bagdogra?.id || null)}, 'road', NULL, ${num(g.coords.lat)}, ${num(g.coords.lng)},
${q(g.route + ' | Accessibility: ' + g.accessibility + ' | Safety: ' + g.safetyWarnings + ' | Approximate coordinates only.')}, ${q(g.source)});`);
}
emit('');

// ---- shared taxi stands and routes ----------------------------------------
const standIds = new Map();
for (const r of sharedRoutes) {
  const sid = 'stand_' + slug(r.stand);
  if (!standIds.has(sid)) {
    const from = places.find((p) => p.id === r.fromId);
    standIds.set(sid, r.stand);
    emit(`INSERT INTO public.taxi_stands (id, name, lat, lng, operator, permit_note) VALUES
(${q(sid)}, ${q(r.stand)}, ${num(from.lat)}, ${num(from.lng)}, ${q(r.operator)}, ${q(r.permitNote)}) ON CONFLICT (id) DO NOTHING;`);
  }
  emit(`INSERT INTO public.shared_taxi_routes (id, from_place_id, to_place_id, stand_id, operator, fare_paise, seats_total, seats_available, departure_time, frequency, active)
VALUES (${q(r.id)}, ${q(r.fromId)}, ${q(r.toId)}, ${q(sid)}, ${q(r.operator)}, ${num(r.pricePaise)}, ${num(r.seatsTotal)}, ${num(r.seatsTotal)},
${q(r.departureTimes[0])}::time, ${q(r.departureTimes.join(', '))}, true) ON CONFLICT (id) DO NOTHING;`);
}
emit('');

// ---- properties, rooms, availability --------------------------------------
for (const p of properties) {
  emit(`INSERT INTO public.properties (id, destination_id, name, property_type, service, description, lat, lng, amenities, house_rules, cancellation, data_class, image_status)
VALUES (${q(p.id)}, ${q(p.destinationId)}, ${q(p.name)}, ${q(p.propertyType)}, ${q(p.service)}, ${q(p.description)}, ${num(p.coords.lat)}, ${num(p.coords.lng)},
${arr(p.amenities)}, ${q(p.houseRules)}, ${q(p.cancellationPolicy)}, ${q(p.dataClass)}, ${q(p.image?.status || 'unavailable')}) ON CONFLICT (id) DO NOTHING;`);
  for (const r of p.rooms) {
    emit(`INSERT INTO public.property_rooms (id, property_id, name, capacity, beds, base_price_paise, tax_percent, amenities, total_units)
VALUES (${q(r.id)}, ${q(p.id)}, ${q(r.name)}, ${num(r.capacityAdults)}, 1, ${num(r.nightlyRatePaise)}, ${num(p.taxesPercent || 12)}, ${arr(p.amenities)}, ${num(r.totalRooms)})
ON CONFLICT (id) DO NOTHING;`);
  }
}
emit(`-- Real, bounded availability rows. No fabricated "always available" claims:
INSERT INTO public.room_availability (room_id, day, units_available, price_paise, blocked)
SELECT r.id, d::date, r.total_units, r.base_price_paise, false
FROM public.property_rooms r
CROSS JOIN generate_series(CURRENT_DATE, CURRENT_DATE + interval '89 days', interval '1 day') d
ON CONFLICT (room_id, day) DO NOTHING;`);
emit('');

// ---- restaurants, menus, products -----------------------------------------
for (const r of restaurants) {
  emit(`INSERT INTO public.restaurants (id, destination_id, name, cuisines, description, lat, lng, opening_hours, prep_minutes, data_class, image_status)
VALUES (${q(r.id)}, ${q(r.destinationId)}, ${q(r.name)}, ${arr(r.cuisines)}, ${q(r.description)}, ${num(r.coords.lat)}, ${num(r.coords.lng)},
${jq({ display: r.openingHours })}, ${num(r.prepMinutes)}, ${q(r.dataClass)}, ${q(r.image?.status || 'unavailable')}) ON CONFLICT (id) DO NOTHING;`);
  const menuId = 'menu_' + r.id;
  emit(`INSERT INTO public.restaurant_menus (id, restaurant_id, name, category) VALUES (${q(menuId)}, ${q(r.id)}, ${q('Main menu')}, 'main') ON CONFLICT (id) DO NOTHING;`);
  for (const m of r.menu) {
    emit(`INSERT INTO public.food_products (id, menu_id, restaurant_id, name, description, price_paise, vegetarian, available, customizations, addons, image_status)
VALUES (${q(m.id)}, ${q(menuId)}, ${q(r.id)}, ${q(m.name)}, ${q(m.description)}, ${num(m.pricePaise)}, ${q(m.vegetarian)}, ${q(m.available)},
${jq(m.customizations || [])}, ${jq(m.addons || [])}, 'unavailable') ON CONFLICT (id) DO NOTHING;`);
  }
}
emit('');

// ---- grocery stores, products, independent inventory ----------------------
const categoryMap = {
  'Fruits': 'fruits', 'Vegetables': 'vegetables', 'Dairy': 'dairy', 'Bakery': 'bakery',
  'Snacks': 'snacks', 'Beverages': 'beverages', 'Household': 'household',
  'Personal care': 'personal-care', 'Packaged foods': 'packaged-foods', 'Local products': 'local-products',
};
for (const s of groceryStores) {
  const dest = destinations.find((d) => d.id === s.destinationId);
  emit(`INSERT INTO public.grocery_stores (id, destination_id, name, description, lat, lng, delivery_radius_km, delivery_coverage, delivery_slots, data_class)
VALUES (${q(s.id)}, ${q(s.destinationId)}, ${q(s.name)}, ${q(s.description)}, ${num(s.coords.lat)}, ${num(s.coords.lng)}, ${num(s.deliveryCoverageKm)},
${arr([dest?.name || s.destinationId])}, ${jq(s.slots)}, ${q(s.dataClass)}) ON CONFLICT (id) DO NOTHING;`);
  for (const p of s.products) {
    emit(`INSERT INTO public.grocery_products (id, store_id, name, category, variant, unit, price_paise, image_status)
VALUES (${q(p.id)}, ${q(s.id)}, ${q(p.name)}, ${q(categoryMap[p.category] || 'other')}, 'standard', ${q(p.unit)}, ${num(p.pricePaise)}, 'unavailable')
ON CONFLICT (id) DO NOTHING;`);
    emit(`INSERT INTO public.grocery_inventory (store_id, product_id, stock) VALUES (${q(s.id)}, ${q(p.id)}, ${num(p.stock)})
ON CONFLICT (store_id, product_id) DO NOTHING;`);
  }
}
emit('');

// ---- tourism packages, activities and experiences -------------------------
for (const p of packages) {
  emit(`INSERT INTO public.tour_packages (id, destination_id, name, description, duration_hours, price_paise, capacity, data_class)
VALUES (${q(p.id)}, ${q(p.destinationId)}, ${q(p.name)}, ${q(p.description)}, ${num(p.durationHours)}, ${num(p.pricePaise)}, 12, 'demo-listing')
ON CONFLICT (id) DO NOTHING;`);
}
for (const a of attractions) {
  emit(`INSERT INTO public.tour_activities (id, destination_id, name, kind, duration_minutes, price_paise, lat, lng, description)
VALUES (${q('act_' + a.id)}, ${q(a.destinationId)}, ${q(a.name)}, 'sightseeing', ${num(a.typicalVisitMinutes || 60)}, 0,
${num(a.coords.lat)}, ${num(a.coords.lng)}, ${q(a.description)}) ON CONFLICT (id) DO NOTHING;`);
}
for (const e of experiences) {
  emit(`INSERT INTO public.tour_activities (id, destination_id, name, kind, duration_minutes, price_paise, description)
VALUES (${q(e.id)}, ${q(e.destinationId)}, ${q(e.name)}, 'experience', ${num(e.durationMinutes)}, ${num(e.pricePaise)}, ${q(e.description)})
ON CONFLICT (id) DO NOTHING;`);
}
emit(`INSERT INTO public.coupons (code, kind, value, min_subtotal_paise, max_discount_paise, active) VALUES
('GOWAYY10', 'percent', 10, 50000, 20000, true),
('FLAT100', 'flat', 10000, 80000, NULL, true)
ON CONFLICT (code) DO NOTHING;`);
emit('');

// ---- exact shared catalogue document --------------------------------------
const document = {
  destinations, hiddenGems, attractions, places, vehicles,
  sharedRoutes, properties, restaurants, stores: groceryStores, packages, experiences,
};
emit(`INSERT INTO public.catalog_documents (id, document) VALUES ('catalog', ${jq(document)})
ON CONFLICT (id) DO UPDATE SET document = EXCLUDED.document, updated_at = now();`);
emit('');
emit('COMMIT;');

const target = join(root, 'supabase', 'seed', '0001_catalog.sql');
writeFileSync(target, out.join('\n') + '\n');
console.log(`wrote ${target} (${out.length} statements, ${Buffer.byteLength(out.join('\n'))} bytes)`);
